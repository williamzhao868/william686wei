function buildHrPeerExpansion(article) {
  const companyNames = (article.companies || [])
    .map((company) => company.zh || company.en || '')
    .filter(Boolean)
    .join('、');
  const englishCompanies = (article.companies || [])
    .map((company) => company.en || company.zh || '')
    .filter(Boolean)
    .join(', ');
  const focusCompanyText = companyNames || englishCompanies || '这类公司';
  const categoryText = [...(article.category || []), ...(article.tags || [])].filter(Boolean).join('、') || 'HR Tech';
  const keywordText = (article.keywords || []).filter(Boolean).join('、') || '人才、组织和工作流';

  return `## 深度竞品拆解

这条动向不能只当作一条公司新闻来看。放在全球 HR Tech 竞争里，它更像是一个信号：${focusCompanyText} 正在围绕 ${categoryText} 继续加深产品、数据、服务和客户关系的绑定。对买方来说，真正关心的不是某个功能是否听起来先进，而是它能否减少招聘、用工、薪酬、合规、学习或劳动力管理里的实际摩擦。

## 对市场格局的含义

HR Tech 的竞争正在从“单点工具”转向“工作流控制权”。谁能更早进入客户的核心流程，谁就更容易拿到持续数据、复购预算和跨模块扩展机会。${focusCompanyText} 的价值也要放在这个逻辑里判断：它不只是提供一个产品，而是在尝试成为客户组织运行中的一层基础设施。

这也意味着竞品监测不能只看发布内容，还要看三个问题。第一，它影响的是前台招聘、后台合规，还是管理决策。第二，它是否和企业已有系统连接，比如 ATS、HCM、薪酬、绩效、学习或 BI。第三，它是否能形成可持续的数据闭环，让产品越用越了解岗位、员工、候选人或组织结构。

## 对 Engma 的价值

对 Engma 的启发：这条动向不只是“同行在做什么”，而是在提醒我们要持续拆解 ${focusCompanyText} 背后的产品结构、交付节奏和商业路径。尤其是 ${keywordText} 相关主题，适合沉淀成客户简报、内部培训和销售沟通里的固定观察框架。

可落地机会：Engma 后面可以把这类信息继续拆成“产品信号 / 客户价值 / 组织影响 / 可复用表达”四层。产品信号帮助判断竞品在推什么；客户价值帮助判断它为什么有人买单；组织影响帮助判断它改变了哪个岗位或流程；可复用表达则让内容不只停留在网页文章，而是能进入客户会议、方案材料和内部知识库。

## 后续跟踪建议

后续建议持续跟踪三类变化。第一，${focusCompanyText} 是否把 AI、自动化或数据分析真正嵌进核心流程，而不是只做营销表达。第二，它是否在不同区域市场形成差异化打法，例如欧美市场更强调合规和效率，亚太市场更强调本地化交付和服务网络。第三，它是否出现生态合作、并购、开放 API 或行业模板，这些通常比单个功能发布更能说明长期方向。

我们可以怎么用：把它和 Engma 现有的全球 AI 洞察、AI 工具测试、竞品监测串起来，形成更稳定的观察模板。这样每一条 HR Tech 内容都能回答同一个问题：这家公司到底在控制哪段工作流，客户为什么需要它，Engma 可以从中提炼什么可复用方法。`;
}

function enrichHrPeerArticle(article, index = 0) {
  if (!article) {
    return article;
  }
  return {
    ...article,
    imageUrl: getHrPeerCoverImage(index),
    fullContent: article.fullContent || article.summary || '',
    zh: article.zh
      ? {
          ...article.zh,
          fullContent: article.zh.fullContent || article.zh.summary || article.fullContent || article.summary || '',
        }
      : {
          title: article.title,
          summary: article.summary,
          fullContent: article.fullContent || article.summary || '',
          category: article.category,
          tags: article.tags,
        },
  };
}

